package access

// Rule is what an API route asks of the account calling it. Staff routes are never open to the
// reseller tier: they act on every user at once or on the panel's own records.
type Rule struct {
	Perm  string
	Staff bool
}

func any_() Rule             { return Rule{Perm: permissionAny} }
func need(p string) Rule     { return Rule{Perm: p} }
func staff(p string) Rule    { return Rule{Perm: p, Staff: true} }
func key(m, p string) string { return m + " " + p }

