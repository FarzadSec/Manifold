// RouteRule returns the rule for an API route, path relative to /panel/api.
func RouteRule(method, path string) (Rule, bool) {
	r, ok := routeRules[key(method, path)]
	return r, ok
}

// RuledRoutes lists every route that has a rule, for the contract test.
func RuledRoutes() []string {
	out := make([]string, 0, len(routeRules))
	for k := range routeRules {
		out = append(out, k)
	}
	return out
}
